CREATE TABLE IF NOT EXISTS entries (
 id INTEGER PRIMARY KEY AUTO_INCREMENT,
 kind VARCHAR(30) NOT NULL,
 title VARCHAR(240) NOT NULL,
 slug VARCHAR(240) NOT NULL UNIQUE,
 category VARCHAR(80) NOT NULL DEFAULT '',
 summary TEXT NOT NULL,
 content LONGTEXT NOT NULL,
 metadata LONGTEXT NOT NULL,
 published INTEGER NOT NULL DEFAULT 0,
 created_at VARCHAR(30) NOT NULL,
 updated_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS inquiries (
 id INTEGER PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 company VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(40) NOT NULL,
 project_type VARCHAR(80) NOT NULL,
 budget VARCHAR(80) NOT NULL,
 description TEXT NOT NULL,
 attachment VARCHAR(100) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'New',
 created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS rate_limits (bucket VARCHAR(64) PRIMARY KEY, hits INTEGER NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS settings (name VARCHAR(100) PRIMARY KEY, value LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS site_requests (id INTEGER PRIMARY KEY AUTO_INCREMENT,name VARCHAR(120) NOT NULL,company VARCHAR(160) NOT NULL,email VARCHAR(254) NOT NULL,phone VARCHAR(40) NOT NULL,website_type VARCHAR(80) NOT NULL,budget VARCHAR(80) NOT NULL,timeline VARCHAR(80) NOT NULL,features TEXT NOT NULL,reference_url VARCHAR(500) NOT NULL,status VARCHAR(30) NOT NULL DEFAULT 'New',created_at VARCHAR(30) NOT NULL);
CREATE TABLE IF NOT EXISTS reviews (id INTEGER PRIMARY KEY AUTO_INCREMENT,name VARCHAR(120) NOT NULL,company VARCHAR(160) NOT NULL,reviewer_role VARCHAR(120) NOT NULL,rating INTEGER NOT NULL,review TEXT NOT NULL,status VARCHAR(30) NOT NULL DEFAULT 'Pending',created_at VARCHAR(30) NOT NULL,updated_at VARCHAR(30) NOT NULL);
CREATE TABLE IF NOT EXISTS partners (id INTEGER PRIMARY KEY AUTO_INCREMENT,name VARCHAR(180) NOT NULL,url VARCHAR(500) NOT NULL,description TEXT NOT NULL,logo_url VARCHAR(500) NOT NULL,featured INTEGER NOT NULL DEFAULT 0,visible INTEGER NOT NULL DEFAULT 0,sort_order INTEGER NOT NULL DEFAULT 0,created_at VARCHAR(30) NOT NULL,updated_at VARCHAR(30) NOT NULL);
