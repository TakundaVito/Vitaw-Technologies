CREATE TABLE IF NOT EXISTS entries (
 id INTEGER PRIMARY KEY AUTO_INCREMENT,
 kind VARCHAR(30) NOT NULL,
 title VARCHAR(240) NOT NULL,
 slug VARCHAR(240) NOT NULL UNIQUE,
 category VARCHAR(80) NOT NULL DEFAULT '',
 summary TEXT NOT NULL,
 content LONGTEXT NOT NULL,
 metadata LONGTEXT NOT NULL,
 published INTEGER NOT NULL DEFAULT 0,
 created_at VARCHAR(30) NOT NULL,
 updated_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS inquiries (
 id INTEGER PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 company VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(40) NOT NULL,
 project_type VARCHAR(80) NOT NULL,
 budget VARCHAR(80) NOT NULL,
 description TEXT NOT NULL,
 attachment VARCHAR(100) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'New',
 created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS rate_limits (bucket VARCHAR(64) PRIMARY KEY, hits INTEGER NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS settings (name VARCHAR(100) PRIMARY KEY, value LONGTEXT NOT NULL);
